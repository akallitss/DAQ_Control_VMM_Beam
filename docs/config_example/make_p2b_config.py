#!/usr/bin/env python3
"""Generate p2basket-sc configuration files for an arbitrary set of hybrids.

Two sub-commands:

  base  Write a base YAML (the full register map) for the hybrids you list,
        starting from the 10-hybrid CERN base YAML. Every hybrid block in that
        file is identical except for its `id` and `alias`, so the hybrid[00]
        block is copied once per requested hybrid. The FEC / DAQ IP addresses
        can be set at the same time.

  ext   Write an "ext" file (the per-VMM overrides applied on top of the base
        YAML by p2basket_sc_config.py): gain, peaking time, polarity, neighbour
        logic, SFM, threshold, and optional channel masks.

Examples
  # base YAML for hybrids 0-15 on a FEC at 192.168.0.12, DAQ NIC 192.168.0.14
  ./make_p2b_config.py base --hybrids 0-15 --ip-fec 192.168.0.12 \
        --ip-daq 192.168.0.14 -o p2b-config-16hyb-base.yaml

  # ext file: gain 4.5 mV/fC, 200 ns, threshold 220 DAC on hybrids 1-15,
  # plus a trigger hybrid 0 with its own settings, and two masked channels
  ./make_p2b_config.py ext --hybrids 1-15 --gain 4.5 --peaktime 200 \
        --threshold 220 --mask 3:0:17 --mask 5:1:40-42 -o my-ext.txt

Then on the DAQ machine:
  ./p2basket_sc_config.py -c <dir> -b p2b-config-16hyb-base.yaml -e my-ext.txt
"""
import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_TEMPLATE = HERE / "p2b-config-cern-base_10hyb.yaml"

GAIN_CODE = {0.5: 0, 1.0: 1, 3.0: 2, 4.5: 3, 6.0: 4, 9.0: 5, 12.0: 6, 16.0: 7}  # sg, mV/fC
PEAK_CODE = {200: 0, 100: 1, 50: 2, 25: 3}                                     # st, ns


def parse_ids(text):
    """'0-3,5,8-9' -> [0, 1, 2, 3, 5, 8, 9]"""
    out = []
    for part in text.split(","):
        part = part.strip()
        if not part:
            continue
        if "-" in part:
            a, b = part.split("-")
            out.extend(range(int(a), int(b) + 1))
        else:
            out.append(int(part))
    return sorted(set(out))


# --------------------------------------------------------------------------- base
HYB_START = re.compile(r"^ {8}- id +: \d+$")


def split_template(lines):
    starts = [i for i, l in enumerate(lines)
              if HYB_START.match(l) and i + 1 < len(lines) and "type     : Hybrid" in lines[i + 1]]
    if not starts:
        sys.exit("template: no hybrid blocks found")
    preamble = lines[:starts[0]]
    block = lines[starts[0]:starts[1] if len(starts) > 1 else len(lines)]
    # strip trailing blank lines of the block, re-add a fixed separator later
    while block and not block[-1].strip():
        block.pop()
    if "alias    : hybrid[00]" not in block[2]:
        sys.exit("template: first hybrid block is not hybrid[00]")
    return preamble, block


def set_ip(preamble, alias, ip):
    for i, l in enumerate(preamble):
        if re.match(r"^\s+alias\s+: " + alias + r"$", l):
            for j in range(i, i + 8):
                if re.match(r"^\s+value\s+: ", preamble[j]):
                    preamble[j] = re.sub(r": .*$", ": " + ip, preamble[j])
                    return
    sys.exit(f"template: register {alias} not found")


def cmd_base(a):
    lines = Path(a.template).read_text().split("\n")
    preamble, block = split_template(lines)
    if a.ip_fec:
        set_ip(preamble, "ip_fec", a.ip_fec)
    if a.ip_daq:
        set_ip(preamble, "ip_daq", a.ip_daq)
    out = list(preamble)
    for h in parse_ids(a.hybrids):
        b = list(block)
        b[0] = re.sub(r": \d+$", f": {h}", b[0])
        b[2] = b[2].replace("hybrid[00]", f"hybrid[{h:02d}]")
        out.extend(b)
        out.extend(["", ""])
    Path(a.output).write_text("\n".join(out) + "\n")
    print(f"wrote {a.output}: hybrids {parse_ids(a.hybrids)}")


# --------------------------------------------------------------------------- ext
def parse_mask(text):
    """'hyb:vmm:ch[-ch][,ch...]' -> (hyb, vmm, [channels])"""
    try:
        h, v, chs = text.split(":")
        return int(h), int(v), parse_ids(chs)
    except ValueError:
        sys.exit(f"--mask {text!r}: expected hyb:vmm:channels, e.g. 3:0:17 or 5:1:40-42")


def cmd_ext(a):
    if a.gain not in GAIN_CODE:
        sys.exit(f"--gain must be one of {sorted(GAIN_CODE)}")
    if a.peaktime not in PEAK_CODE:
        sys.exit(f"--peaktime must be one of {sorted(PEAK_CODE)}")
    if not 0 <= a.threshold <= 1023:
        sys.exit("--threshold is a 10-bit DAC value (0-1023)")
    sg, st = GAIN_CODE[a.gain], PEAK_CODE[a.peaktime]
    lo, hi = a.threshold % 64, a.threshold // 64
    hybs = parse_ids(a.hybrids)
    R = "Sys 0 Bec {fec} Hyb {h} Vmm {v} Reg {reg:<11} Field {f:<4} {val:>3}"

    o = ["#" * 64,
         "# p2basket ext file generated by make_p2b_config.py",
         "# Format: Sys {sys} Bec {fec} Hyb {hyb} Vmm {vmm} Reg {register} Field {field} {value}",
         "# Only lines that name a Vmm are applied; lines are applied in order (last one wins).",
         "#" * 64, ""]
    for h in hybs:
        o.append(f"# ---- Hybrid {h}")
        for v in (0, 1):
            k = dict(fec=a.fec, h=h, v=v)
            o.append(R.format(**k, reg="bank1spi2", f="sg", val=sg) + f"   # gain {a.gain} mV/fC")
            o.append(R.format(**k, reg="bank1spi2", f="st", val=st) + f"   # peaking time {a.peaktime} ns")
            o.append(R.format(**k, reg="bank1spi2", f="sp", val=a.polarity) + "   # polarity 0 = negative")
            o.append(R.format(**k, reg="bank1spi2", f="sng", val=a.neighbour) + "   # neighbour logic")
            o.append(R.format(**k, reg="bank1spi2", f="sfm", val=a.sfm))
            o.append(R.format(**k, reg="bank1spi1", f="sdt", val=lo) + f"   # threshold {a.threshold} = {hi}*64 + {lo}")
            o.append(R.format(**k, reg="bank1spi2", f="sdt", val=hi))
        o.append("")
    masks = [parse_mask(m) for m in a.mask]
    if masks:
        o.append("# ---- Masked channels (sm 1 = masked, sm 0 = enabled)")
        for h, v, chs in masks:
            for c in chs:
                o.append(R.format(fec=a.fec, h=h, v=v, reg=f"channel[{c:02d}]", f="sm", val=1))
        o.append("")
    Path(a.output).write_text("\n".join(o) + "\n")
    print(f"wrote {a.output}: hybrids {hybs}, sg={sg} st={st} sdt={a.threshold} ({hi}/{lo}), "
          f"{sum(len(c) for _, _, c in masks)} masked channels")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)

    b = sub.add_parser("base", help="write a base YAML for a list of hybrids")
    b.add_argument("--hybrids", required=True, help="e.g. 0-15 or 0-7,10,11")
    b.add_argument("--template", default=str(DEFAULT_TEMPLATE))
    b.add_argument("--ip-fec", help="FEC IP address (CERN lab default 192.168.0.12)")
    b.add_argument("--ip-daq", help="IP of the DAQ-PC NIC on the FEC subnet")
    b.add_argument("-o", "--output", required=True)
    b.set_defaults(func=cmd_base)

    e = sub.add_parser("ext", help="write an ext (override) file")
    e.add_argument("--hybrids", required=True)
    e.add_argument("--fec", type=int, default=0, help="FEC id (the 'Bec' keyword)")
    e.add_argument("--gain", type=float, default=4.5, help="mV/fC: 0.5 1 3 4.5 6 9 12 16")
    e.add_argument("--peaktime", type=int, default=200, help="ns: 200 100 50 25")
    e.add_argument("--threshold", type=int, default=300, help="global threshold DAC, 0-1023")
    e.add_argument("--polarity", type=int, default=0, choices=(0, 1))
    e.add_argument("--neighbour", type=int, default=0, choices=(0, 1))
    e.add_argument("--sfm", type=int, default=1, choices=(0, 1))
    e.add_argument("--mask", action="append", default=[], help="hyb:vmm:channels, repeatable")
    e.add_argument("-o", "--output", required=True)
    e.set_defaults(func=cmd_ext)

    a = p.parse_args()
    a.func(a)


if __name__ == "__main__":
    main()
